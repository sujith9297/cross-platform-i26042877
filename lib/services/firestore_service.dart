import 'dart:async';
import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/stock_item.dart';

class FirestoreService {
  static final FirestoreService _instance = FirestoreService._internal();
  factory FirestoreService() => _instance;
  FirestoreService._internal();

  static const String collectionName = 'stockItems';
  final FirebaseFirestore _firestore = FirebaseFirestore.instance;

  /// Stream of stock items from Cloud Firestore
  Stream<List<StockItem>> getStockItems() {
    return _firestore
        .collection(collectionName)
        .snapshots()
        .map((snapshot) {
          final items = snapshot.docs.map((doc) => StockItem.fromFirestore(doc)).toList();
          // Sort default by createdAt descending (newest first)
          items.sort((a, b) {
            if (a.createdAt == null && b.createdAt == null) return 0;
            if (a.createdAt == null) return 1;
            if (b.createdAt == null) return -1;
            return b.createdAt!.compareTo(a.createdAt!);
          });
          return items;
        });
  }

  /// Add a new stock item to Cloud Firestore
  /// Document ID is auto-generated by Firestore as per specification
  Future<DocumentReference<Map<String, dynamic>>> addStockItem({
    required String sku,
    required String itemName,
    required String category,
    required int quantity,
    required double unitPrice,
    required int reorderLevel,
  }) async {
    final Map<String, dynamic> data = {
      'sku': sku.trim().toUpperCase(),
      'itemName': itemName.trim(),
      'category': category.trim(),
      'quantity': quantity,
      'unitPrice': unitPrice,
      'reorderLevel': reorderLevel,
      'createdAt': FieldValue.serverTimestamp(),
    };

    // Awaits acknowledged write from Firestore
    return await _firestore.collection(collectionName).add(data);
  }
}
